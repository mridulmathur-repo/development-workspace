package com.workflowautomation.jiraplanner.jira;

import com.workflowautomation.jiraplanner.planning.AcceptanceCriterion;
import com.workflowautomation.jiraplanner.planning.StoryPlan;
import org.springframework.stereotype.Component;
import tools.jackson.databind.JsonNode;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

@Component
public class AtlassianDocumentFactory {

    public String toPlainText(JsonNode document) {
        if (document == null || document.isMissingNode() || document.isNull()) {
            return "";
        }
        List<String> fragments = new ArrayList<>();
        collectText(document, fragments);
        return String.join(" ", fragments).trim();
    }

    public Map<String, Object> storyDescription(StoryPlan story) {
        List<Map<String, Object>> content = new ArrayList<>();
        content.add(paragraph(story.description()));
        content.add(heading("Acceptance criteria", 2));
        for (AcceptanceCriterion criterion : story.acceptanceCriteria()) {
            content.add(paragraph("GIVEN " + criterion.given()));
            content.add(paragraph("WHEN " + criterion.when()));
            content.add(paragraph("THEN " + criterion.then()));
        }
        content.add(paragraph("Generated by Jira AI Planner MVP1."));
        return document(content);
    }

    public Map<String, Object> taskDescription(String storyKey, StoryPlan story, JiraGateway.TaskKind kind) {
        List<Map<String, Object>> content = new ArrayList<>();
        content.add(paragraph(kind.displayName() + " work for generated story " + storyKey + "."));
        content.add(paragraph(story.description()));
        content.add(heading("Definition of done", 2));
        if (kind == JiraGateway.TaskKind.DEVELOPMENT) {
            content.add(paragraph("Implementation satisfies every acceptance criterion on " + storyKey + "."));
            content.add(paragraph("The project builds and automated tests pass."));
        } else {
            content.add(paragraph("Create or execute tests covering every acceptance criterion on " + storyKey + "."));
            content.add(paragraph("Record test results and any failures in Jira."));
        }
        return document(content);
    }

    public Map<String, Object> comment(String text) {
        return document(List.of(paragraph(text)));
    }

    private Map<String, Object> document(List<Map<String, Object>> content) {
        return Map.of("type", "doc", "version", 1, "content", content);
    }

    private Map<String, Object> paragraph(String text) {
        Map<String, Object> paragraph = new LinkedHashMap<>();
        paragraph.put("type", "paragraph");
        paragraph.put("content", List.of(Map.of("type", "text", "text", safe(text))));
        return paragraph;
    }

    private Map<String, Object> heading(String text, int level) {
        return Map.of(
                "type", "heading",
                "attrs", Map.of("level", level),
                "content", List.of(Map.of("type", "text", "text", text))
        );
    }

    private void collectText(JsonNode node, List<String> fragments) {
        if (node.has("text") && node.get("text").isTextual()) {
            fragments.add(node.get("text").asText());
        }
        JsonNode children = node.get("content");
        if (children != null && children.isArray()) {
            children.forEach(child -> collectText(child, fragments));
        }
    }

    private String safe(String value) {
        return value == null ? "" : value;
    }
}
